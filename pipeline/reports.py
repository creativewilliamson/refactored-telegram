TEST_ZIPS = [
    ("46052", "Lebanon, IN", "home pilot"),
    ("10001", "New York, NY", "dense"),
    ("78205", "San Antonio, TX", "big military city"),
    ("20001", "Washington, DC", "DC"),
    ("59301", "Miles City, MT", "rural, must auto-widen"),
    ("87301", "Gallup, NM", "rural"),
    ("04401", "Bangor, ME", "Northeast regional offers"),
    ("82001", "Cheyenne, WY", "small state"),
    ("99701", "Fairbanks, AK", "Alaska"),
    ("96813", "Honolulu, HI", "Hawaii"),
    ("00901", "San Juan, PR", "territory"),
    ("96910", "Hagåtña, GU", "territory with little data"),
    ("00802", "St. Thomas, VI", "territory with little data"),
]


def coverage(brands_doc: dict, stats: dict, choices: dict, records: list[dict], zips: dict,
             data: dict, places: list[dict]) -> str:
    brands = brands_doc["brands"]
    today = dt.date.today().isoformat()
    lines = [
        "# Coverage report",
        "",
        f"Generated by `python -m pipeline.build` on {today}. Locations come only from All The Places "
        "(filtered to the U.S. and territories and to each brand's checked Wikidata Q-id) and from "
        "hand-entered single places in data/places.json.",
        "",
        "## Locations per brand",
        "",
        "| Brand | Spider (run) | Features | Kept | Expected U.S. (approx.) | Flag |",
        "|---|---|---:|---:|---:|---|",
    ]
    for slug in sorted(stats, key=lambda s: brands[s]["name"].lower()):
        st = stats[slug]
        b = brands[slug]
        exp = b.get("expected_us")
        flag = "LOW (under 50% of expected)" if exp and st.kept < 0.5 * exp else ""
        runs = ", ".join(f"{sp} ({(choices.get(sp) or ('none',))[0][:10]})" for sp in st.spiders)
        lines.append(f"| {b['name']} | {runs} | {st.features} | {st.kept} | {exp or ''} | {flag} |")
    lines += [
        "",
        "Dropped along the way (all brands): "
        f"wrong brand Q-id {sum(s.wrong_brand for s in stats.values())}, "
        f"marked by the source as test/lab, closed, coming soon or staff-only "
        f"{sum(s.not_public for s in stats.values())}, "
        f"outside the U.S. {sum(s.not_us for s in stats.values())}, "
        f"no coordinates and no usable address {sum(s.no_place for s in stats.values())}, "
        f"coordinates far from their ZIP or outside the U.S. {sum(s.bad_coords for s in stats.values())}, "
        f"duplicates {sum(s.duplicates for s in stats.values())}. "
        f"Placed with the U.S. Census Geocoder: {sum(s.geocoded for s in stats.values())}. "
        f"Placeholder phone numbers removed (store kept, no phone shown): "
        f"{sum(s.placeholder_phone for s in stats.values())}. "
        f"State corrected to the ZIP's state: {sum(s.state_fixed for s in stats.values())}. "
        f"ZIP hidden because it contradicts the store's own town: {sum(s.zip_hidden for s in stats.values())}.",
        "",
        f"Total store locations: **{len(records)}**. Single places: **{len(places)}**.",
        "",
        "## Offers with at least one location",
        "",
    ]
    kinds = {}
    for o in data["offers"]:
        kinds.setdefault(o["kind"], []).append(o)
    with_loc = len(kinds.get("stores", [])) + len(kinds.get("place", []))
    total = len(data["offers"])
    lines += [
        f"- {with_loc} of {total} offers ({100 * with_loc / total:.0f}%) have at least one mapped location.",
        f"- {len(kinds.get('find', []))} offers are chains with no usable store list: they show a "
        "\"Find nearest\" map link (see data/missing-brands.md).",
        f"- {len(kinds.get('everywhere', []))} offers have no store at all and show in \"Everywhere\": "
        + ", ".join(o["name"] for o in kinds.get("everywhere", [])) + ".",
        "",
        "## Test ZIPs (SPEC section 7)",
        "",
        "| ZIP | Place | Why | Locations within 25 mi | within 100 mi | Single places within 150 mi |",
        "|---|---|---|---:|---:|---:|",
    ]
    for code, place, why in TEST_ZIPS:
        z = zips.get(code)
        if not isinstance(z, list):
            lines.append(f"| {code} | {place} | {why} | ZIP NOT FOUND | | |")
            continue
        lat, lng = z[0], z[1]
        n25 = n100 = 0
        for r in records:
            if abs(r["la"] - lat) > 1.6:
                continue
            d = miles(lat, lng, r["la"], r["lo"])
            if d <= 100:
                n100 += 1
                if d <= 25:
                    n25 += 1
        p150 = sum(1 for p in places if miles(lat, lng, p["la"], p["lo"]) <= 150)
        lines.append(f"| {code} | {place} | {why} | {n25} | {n100} | {p150} |")
    lines.append("")
    return "\n".join(lines)


def missing_brands(brands_doc: dict, data: dict) -> str:
    brands = brands_doc["brands"]
    by_id = {o["id"]: o for o in data["offers"]}
    rows = []
    for slug, b in sorted(brands.items(), key=lambda kv: kv[1]["name"].lower()):
        offers = [by_id[o] for o in b["offers"] if o in by_id]
        if not offers or offers[0]["kind"] != "find":
            continue
        if b.get("atp_spider_without_wikidata"):
            why = (f"All The Places spider `{b['atp_spider_without_wikidata']}` exists, but its stores carry "
                   "no brand:wikidata, so the brand match can't be proven (SPEC 6.2).")
        elif b.get("atp_spiders"):
            why = "All The Places spider returned no usable U.S. stores in the runs checked."
        else:
            why = "No All The Places spider found."
        q = ", ".join(b.get("brand_wikidata") or []) or "unknown"
        where = ", ".join(offers[0].get("states") or []) or "nationwide"
        rows.append(f"| {b['name']} | {q} | {where} | {why} |")
    return "\n".join([
        "# Brands without store locations",
        "",
        "These offers stay on the site. Instead of store cards they get a \"Find nearest\" link that "
        "opens a Google Maps search for the brand near the visitor's town (only when the visitor taps it). "
        "No Overpass/OpenStreetMap fallback was used this run.",
        "",
        "| Brand | Wikidata | Where | Why no stores |",
        "|---|---|---|---|",
        *rows,
        "",
    ])


def write(name: str, text: str) -> None:
    (config.DATA / name).write_text(text, encoding="utf-8", newline="\n")
